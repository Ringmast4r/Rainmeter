# Writes Links/Links.ini, the NWModern Scanner Darkly card. Run with py -3.13; edit this file, never the INI.
# The card only holds empty tiles: Fleet.py reads the registry and checks every URL, Fleet.lua fills the tiles.
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]   # skin root folder
OUT = ROOT / "Links/Links.ini"

COLS, ROWS = 3, 10                      # 30 tiles; a longer list scrolls by row
TW, TH, GAP, PAD = 240, 52, 10, 18
PITCH = TH + 6
W = PAD * 2 + TW * COLS + GAP * (COLS - 1)   # 776
RIGHT = W - PAD
GRID_Y = 108
GRID_END = GRID_Y + PITCH * ROWS - 6
H = GRID_END + 42
SW = (W - PAD * 2 - GAP * 3) / 4          # four stat tiles across the top

TILE = "Rectangle {x},{y},{w},{h},10 | Fill Color {fill} | StrokeWidth 1 | Stroke Color {line}"
TILE_OFF = dict(fill="#cTile#", line="255,255,255,12")
TILE_ON = dict(fill="255,255,255,22", line="94,206,255,110")

s = f"""[Rainmeter]
Update=1000
AccurateText=1
DynamicWindowSize=0
OnRefreshAction=[!CommandMeasure mRun "Run"]
MouseScrollUpAction=[!CommandMeasure mScript "Scroll(-1)"]
MouseScrollDownAction=[!CommandMeasure mScript "Scroll(1)"]
ContextTitle=Check now
ContextAction=[!CommandMeasure mRun "Run"]
ContextTitle2=Open the settings file
ContextAction2=["#@#Local\\settings.txt"]

[Metadata]
Name=NWModern Scanner Darkly
Author=ringmast4r
Information=Every URL in the Scanner Darkly registry as a tile, checked once a minute: status, response time, address and the scanner's headline stat. Click a tile to open it, click the title for the Scanner Darkly index. Generated by @Resources\\Tools\\generate.py.
Version=0.1.0
License=Creative Commons BY-NC-SA 4.0

[Variables]
@Include=#@#Palette.inc
Cols={COLS}
Rows={ROWS}
; Demo=1 swaps names and addresses for placeholders (screenshots)
Demo=0

; ---------------- styles
[sTitle]
FontFace=#fMain#
FontSize=9
StringStyle=Bold
StringCase=Upper
FontColor=#cText#
AntiAlias=1

[sCap]
FontFace=#fMain#
FontSize=7
StringStyle=Bold
StringCase=Upper
FontColor=#cText3#
AntiAlias=1

[sTileVal]
FontFace=#fLight#
FontSize=17
FontColor=#cText#
AntiAlias=1

[sTileSub]
FontFace=#fMain#
FontSize=7
FontColor=#cText2#
AntiAlias=1
ClipString=1
H=12

[sName]
FontFace=#fMain#
FontSize=8
StringStyle=Bold
FontColor=#cText#
AntiAlias=1
ClipString=1
H=15

[sAddr]
FontFace=#fMono#
FontSize=7
FontColor=#cText3#
AntiAlias=1
ClipString=1
H=12

[sStat]
FontFace=#fMain#
FontSize=7
FontColor=#cText2#
AntiAlias=1
ClipString=1
H=12

[sMs]
FontFace=#fMono#
FontSize=7
StringAlign=Right
FontColor=#cText3#
AntiAlias=1

; ---------------- measures
[mRun]
Measure=Plugin
Plugin=RunCommand
Program=py.exe
Parameter=-3.13 -I "#@#Scripts\\Fleet.py"
State=Hide
OutputType=UTF8
Timeout=30000
FinishAction=[!CommandMeasure mScript "Parse()"]

[mScript]
Measure=Script
ScriptFile=#@#Scripts\\Fleet.lua

; ---------------- chrome
[MCard]
Meter=Shape
Shape=Rectangle 0.5,0.5,{W - 1},{H - 1},16 | Fill LinearGradient gCard | StrokeWidth 1 | Stroke Color #cLine#
gCard=90 | #cBgTop# ; 0.0 | #cBg# ; 1.0

[MTopBar]
Meter=Shape
Shape=Rectangle {PAD},0,{W - PAD * 2},3,1.5 | Fill LinearGradient gTop | StrokeWidth 0
gTop=0 | #cAccent# ; 0.0 | #cAccent2# ; 1.0

[MDot]
Meter=Shape
Shape=Rectangle {PAD},17,7,7,2 | Fill LinearGradient gDot | StrokeWidth 0
gDot=45 | #cAccent# ; 0.0 | #cAccent2# ; 1.0

[MTitle]
Meter=String
MeterStyle=sTitle
X=32
Y=13
Text=Scanner // Darkly
MouseActionCursorName=Hand

[MSub]
Meter=String
MeterStyle=sCap
X={RIGHT}
Y=15
StringAlign=Right
Text=Every URL in the registry  -  click a tile to open it

[MRule]
Meter=Shape
Shape=Rectangle {PAD},{GRID_Y - 10},{W - PAD * 2},1 | Fill Color #cLine# | StrokeWidth 0
Shape2=Rectangle {PAD},{GRID_END + 10},{W - PAD * 2},1 | Fill Color #cLine# | StrokeWidth 0

[MFoot]
Meter=String
MeterStyle=sCap
StringCase=None
FontColor=#cText3#
X={PAD}
Y={GRID_END + 18}
Text=checking...

[MScroll]
Meter=String
MeterStyle=sCap
StringCase=None
X={RIGHT}
Y={GRID_END + 18}
StringAlign=Right
Text=
"""

# ---------------- stat tiles: links, up, down, slowest
STATS = [("SAll", "URLs", "#cAccent#"), ("SUp", "Answering", "#cGood#"),
         ("SDown", "Down", "#cBad#"), ("SSlow", "Slowest", "#cWarn#")]
for i, (k, cap, col) in enumerate(STATS):
    x = round(PAD + i * (SW + GAP))
    w = round(SW)
    s += f"""
[{k}Bg]
Meter=Shape
Shape=Rectangle {x},32,{w},58,10 | Fill Color #cTile# | StrokeWidth 0

[{k}Cap]
Meter=String
MeterStyle=sCap
X={x + 10}
Y=38
FontColor={col}
Text={cap}

[{k}Val]
Meter=String
MeterStyle=sTileVal
X={x + 8}
Y=45
Text=--

[{k}Sub]
Meter=String
MeterStyle=sTileSub
X={x + 10}
Y=70
W={w - 20}
Text=
"""

# ---------------- link tiles
for r in range(ROWS):
    for c in range(COLS):
        n = r * COLS + c + 1
        x, y = PAD + c * (TW + GAP), GRID_Y + r * PITCH
        g = f"Group=T{n}"
        off = TILE.format(x=x, y=y, w=TW, h=TH, **TILE_OFF)
        on = TILE.format(x=x, y=y, w=TW, h=TH, **TILE_ON)
        s += f"""
[T{n}]
Meter=Shape
Shape={off}
{g}
Hidden=1
MouseOverAction=[!SetOption T{n} Shape "{on}"][!UpdateMeter T{n}][!Redraw]
MouseLeaveAction=[!SetOption T{n} Shape "{off}"][!UpdateMeter T{n}][!Redraw]

[T{n}Dot]
Meter=Shape
Shape=Ellipse {x + 14},{y + 13},6 | Fill Color [#Dot{n}],46 | StrokeWidth 0
Shape2=Ellipse {x + 14},{y + 13},3 | Fill Color [#Dot{n}] | StrokeWidth 0
DynamicVariables=1
{g}
Hidden=1

[T{n}Name]
Meter=String
MeterStyle=sName
X={x + 26}
Y={y + 5}
W={TW - 26 - 58}
{g}
Hidden=1
Text=

[T{n}Ms]
Meter=String
MeterStyle=sMs
X={x + TW - 10}
Y={y + 7}
{g}
Hidden=1
Text=

[T{n}Addr]
Meter=String
MeterStyle=sAddr
X={x + 26}
Y={y + 22}
W={TW - 36}
{g}
Hidden=1
Text=

[T{n}Stat]
Meter=String
MeterStyle=sStat
X={x + 26}
Y={y + 35}
W={TW - 36}
{g}
Hidden=1
Text=
"""

# the status dot colours, one variable per tile so Fleet.lua can set them
s = s.replace("Demo=0\n", "Demo=0\n" + "".join(f"Dot{n}=108,116,134\n" for n in range(1, COLS * ROWS + 1)), 1)

OUT.parent.mkdir(exist_ok=True)
OUT.write_text(s, encoding="utf-8")
print(f"Wrote {OUT} ({COLS} x {ROWS} tiles, {W} x {H})")
