# Writes Links/Links.ini, the NWModern Scanner Darkly card. Run with py -3.13; edit this file, never the INI.
# The card only holds empty rows: Fleet.py reads the registry and checks every URL, Fleet.lua fills the rows.
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]   # skin root folder
OUT = ROOT / "Links/Links.ini"

ROWS = 14                               # rows on screen; the mouse wheel scrolls the rest
W, PAD, RH = 380, 16, 34                # card width, side margin, row height
LW = W - PAD * 2 - 12                   # row width, leaving room for the scrollbar
RIGHT = W - PAD
GRID_Y = 52
GRID_END = GRID_Y + RH * ROWS
H = GRID_END + 40

ROW = "Rectangle {x},{y},{w},{h},8 | Fill Color {fill} | StrokeWidth 0"
ROW_OFF = "255,255,255,9"
ROW_ON = "255,255,255,26"

s = f"""[Rainmeter]
Update=1000
AccurateText=1
DynamicWindowSize=0
OnRefreshAction=[!CommandMeasure mRun "Run"]
MouseScrollUpAction=[!CommandMeasure mScript "Scroll(-1)"]
MouseScrollDownAction=[!CommandMeasure mScript "Scroll(1)"]
ContextTitle=Check now
ContextAction=[!CommandMeasure mRun "Run"]
ContextTitle2=Open the settings file
ContextAction2=["#@#Local\\settings.txt"]

[Metadata]
Name=NWModern Scanner Darkly
Author=ringmast4r
Information=Every URL in the Scanner Darkly registry, one per row, checked once a minute: a status dot, the name and the response time. Scroll for the rest, hover a row for its address and details, click it to open. Click the title for the Scanner Darkly index. Generated by @Resources\\Tools\\generate.py.
Version=0.1.1
License=Creative Commons BY-NC-SA 4.0

[Variables]
@Include=#@#Palette.inc
Rows={ROWS}
; Demo=1 swaps names for placeholders (screenshots)
Demo=0

; ---------------- styles
[sTitle]
FontFace=#fMain#
FontSize=11
StringStyle=Bold
StringCase=Upper
FontColor=#cText#
AntiAlias=1

[sCap]
FontFace=#fMain#
FontSize=9
StringStyle=Bold
FontColor=#cText3#
AntiAlias=1

[sName]
FontFace=#fMain#
FontSize=11
FontColor=#cText#
AntiAlias=1
ClipString=1
H=20

[sMs]
FontFace=#fMono#
FontSize=10
StringAlign=Right
FontColor=#cText3#
AntiAlias=1

; ---------------- measures
[mRun]
Measure=Plugin
Plugin=RunCommand
Program=py.exe
Parameter=-3.13 -I "#@#Scripts\\Fleet.py"
State=Hide
OutputType=UTF8
Timeout=30000
FinishAction=[!CommandMeasure mScript "Parse()"]

[mScript]
Measure=Script
ScriptFile=#@#Scripts\\Fleet.lua

; ---------------- chrome
[MCard]
Meter=Shape
Shape=Rectangle 0.5,0.5,{W - 1},{H - 1},16 | Fill LinearGradient gCard | StrokeWidth 1 | Stroke Color #cLine#
gCard=90 | #cBgTop# ; 0.0 | #cBg# ; 1.0

[MTopBar]
Meter=Shape
Shape=Rectangle {PAD},0,{W - PAD * 2},3,1.5 | Fill LinearGradient gTop | StrokeWidth 0
gTop=0 | #cAccent# ; 0.0 | #cAccent2# ; 1.0

[MDot]
Meter=Shape
Shape=Rectangle {PAD},20,8,8,2 | Fill LinearGradient gDot | StrokeWidth 0
gDot=45 | #cAccent# ; 0.0 | #cAccent2# ; 1.0

[MTitle]
Meter=String
MeterStyle=sTitle
X={PAD + 15}
Y=14
Text=Scanner // Darkly
MouseActionCursorName=Hand

[MSub]
Meter=String
MeterStyle=sCap
X={RIGHT}
Y=17
StringAlign=Right
Text=checking...

[MFoot]
Meter=String
MeterStyle=sCap
StringStyle=Normal
X={PAD}
Y={GRID_END + 12}
Text=

[MScroll]
Meter=String
MeterStyle=sCap
StringStyle=Normal
X={RIGHT}
Y={GRID_END + 12}
StringAlign=Right
Text=

[RScroll]
Meter=Shape
Shape=Rectangle {RIGHT - 4},{GRID_Y},4,{RH * ROWS - 4},2 | Fill Color 255,255,255,10 | StrokeWidth 0
Shape2=Rectangle {RIGHT - 4},{GRID_Y},4,40,2 | Fill Color #cText3# | StrokeWidth 0
Hidden=1
"""

for n in range(1, ROWS + 1):
    y = GRID_Y + (n - 1) * RH
    g = f"Group=R{n}"
    off = ROW.format(x=PAD, y=y, w=LW, h=RH - 4, fill=ROW_OFF)
    on = ROW.format(x=PAD, y=y, w=LW, h=RH - 4, fill=ROW_ON)
    s += f"""
[R{n}]
Meter=Shape
Shape={off}
{g}
Hidden=1
MouseOverAction=[!SetOption R{n} Shape "{on}"][!UpdateMeter R{n}][!Redraw]
MouseLeaveAction=[!SetOption R{n} Shape "{off}"][!UpdateMeter R{n}][!Redraw]

[R{n}Dot]
Meter=Shape
Shape=Ellipse {PAD + 15},{y + 15},7 | Fill Color [#Dot{n}],46 | StrokeWidth 0
Shape2=Ellipse {PAD + 15},{y + 15},4 | Fill Color [#Dot{n}] | StrokeWidth 0
DynamicVariables=1
{g}
Hidden=1

[R{n}Name]
Meter=String
MeterStyle=sName
X={PAD + 30}
Y={y + 5}
W={LW - 30 - 92}
{g}
Hidden=1
Text=

[R{n}Ms]
Meter=String
MeterStyle=sMs
X={PAD + LW - 10}
Y={y + 7}
{g}
Hidden=1
Text=
"""

# the status dot colours, one variable per row so Fleet.lua can set them
s = s.replace("Demo=0\n", "Demo=0\n" + "".join(f"Dot{n}=108,116,134\n" for n in range(1, ROWS + 1)), 1)

OUT.parent.mkdir(exist_ok=True)
OUT.write_text(s, encoding="utf-8")
print(f"Wrote {OUT} ({ROWS} rows, {W} x {H})")
